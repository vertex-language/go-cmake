package eval

import (
	"bufio"
	"bytes"
	"fmt"
	"io"
	"strings"
)

// CMakeCache.txt is what makes a build directory a thing you return to.
//
// Without it, `cmake -B build -DWITH_SSL=ON` followed later by a plain
// `cmake -B build` silently drops WITH_SSL, and the second configure produces a
// different build from the first with nothing to show why. The file is also the
// only record of what a find_package resolved to, so re-configuring without it
// repeats every search.
//
// The format is a flat list of `KEY:TYPE=VALUE` lines with `//` comments
// carrying each entry's help text. It is deliberately editable by hand: that is
// why the type is on the key rather than inferred, and why the help text is
// stored rather than looked up.

const cacheHeader = `# This is the CMakeCache file.
# For build in directory: %s
# It was generated by go-cmake.
# You can edit this file to change values found and used by cmake.
# If you do not want to change any of the values, simply exit the editor.
# If you do want to change a value, simply edit, save, and exit the editor.
# The syntax for the file is as follows:
# KEY:TYPE=VALUE
# KEY is the name of a variable in the cache.
# TYPE is a hint to GUIs for the type of VALUE, DO NOT EDIT TYPE!.
# VALUE is the current value for the KEY.

########################
# EXTERNAL cache entries
########################

`

const cacheInternalHeader = `
########################
# INTERNAL cache entries
########################

`

// WriteCache renders the cache in CMakeCache.txt form.
func WriteCache(w io.Writer, c *Cache, binaryDir string) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, cacheHeader, binaryDir)

	// External entries come first, as the part a person may reasonably edit.
	// Internal ones follow under their own banner, which is the file's way of
	// saying they are CMake's business rather than yours.
	var internal []string
	for _, name := range c.Names() {
		entry, ok := c.Get(name)
		if !ok {
			continue
		}
		if entry.Type == CacheInternal {
			internal = append(internal, name)
			continue
		}
		if entry.DocStr != "" {
			fmt.Fprintf(&b, "//%s\n", entry.DocStr)
		}
		fmt.Fprintf(&b, "%s:%s=%s\n\n", name, CacheTypeName(entry.Type), entry.Value)
	}

	b.WriteString(cacheInternalHeader)
	for _, name := range internal {
		entry, _ := c.Get(name)
		fmt.Fprintf(&b, "%s:INTERNAL=%s\n", name, entry.Value)
	}
	// The advanced marks ride along as internal entries, which is how CMake
	// keeps mark_as_advanced() from having to be re-run on every configure.
	for _, name := range c.Names() {
		if entry, ok := c.Get(name); ok && entry.Advanced {
			fmt.Fprintf(&b, "%s-ADVANCED:INTERNAL=1\n", name)
		}
	}
	_, err := w.Write(b.Bytes())
	return err
}

// ReadCache parses a CMakeCache.txt into a Cache.
//
// A line this parser does not understand is skipped rather than rejected. The
// file is documented as hand-editable, so a stray line is a person's typo, and
// discarding an entire build directory's cache over one is a worse outcome than
// losing the line.
func ReadCache(r io.Reader) (*Cache, error) {
	c := NewCache()
	advanced := map[string]bool{}
	scanner := bufio.NewScanner(r)
	scanner.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)

	doc := ""
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		switch {
		case line == "":
			continue
		case strings.HasPrefix(line, "//"):
			doc = line[2:]
			continue
		case strings.HasPrefix(line, "#"):
			continue
		}

		name, rest, found := strings.Cut(line, ":")
		if !found {
			doc = ""
			continue
		}
		typeName, value, found := strings.Cut(rest, "=")
		if !found {
			doc = ""
			continue
		}

		// The advanced marks are stored as entries; turn them back into the
		// flag they represent rather than leaving them in the table.
		if base, isMark := strings.CutSuffix(name, "-ADVANCED"); isMark && typeName == "INTERNAL" {
			advanced[base] = isOn(value)
			doc = ""
			continue
		}

		c.Set(name, value, parseCacheTypeName(typeName), doc, true)
		doc = ""
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	for name := range advanced {
		if entry, ok := c.Get(name); ok {
			entry.Advanced = true
		}
	}
	return c, nil
}

// CacheTypeName renders a cache entry's type the way CMakeCache.txt spells it.
// It is exported because -L prints the same form, and two renderings of the
// same thing would be one too many.
func CacheTypeName(t CacheEntryType) string {
	switch t {
	case CacheBool:
		return "BOOL"
	case CachePath:
		return "PATH"
	case CacheFilepath:
		return "FILEPATH"
	case CacheInternal:
		return "INTERNAL"
	case CacheStatic:
		return "STATIC"
	case CacheUninitialized:
		return "UNINITIALIZED"
	default:
		return "STRING"
	}
}

// parseCacheTypeName is the inverse, for reading the file back.
func parseCacheTypeName(s string) CacheEntryType {
	switch strings.ToUpper(strings.TrimSpace(s)) {
	case "BOOL":
		return CacheBool
	case "PATH":
		return CachePath
	case "FILEPATH":
		return CacheFilepath
	case "INTERNAL":
		return CacheInternal
	case "STATIC":
		return CacheStatic
	case "UNINITIALIZED":
		return CacheUninitialized
	default:
		return CacheString
	}
}

// Merge copies every entry of other into c that c does not already hold.
// A value already present wins, which is what makes a -D on the command line
// override what a previous configure left behind.
func (c *Cache) Merge(other *Cache) {
	for _, name := range other.Names() {
		if _, exists := c.Get(name); exists {
			continue
		}
		if entry, ok := other.Get(name); ok {
			c.Set(name, entry.Value, entry.Type, entry.DocStr, true)
			if entry.Advanced {
				if e, ok := c.Get(name); ok {
					e.Advanced = true
				}
			}
		}
	}
}

// RemoveMatching deletes every entry whose name matches a CMake globbing
// expression, which is what `cmake -U` takes.
func (c *Cache) RemoveMatching(pattern string) int {
	re, err := compileGlob(pattern)
	if err != nil {
		return 0
	}
	removed := 0
	for _, name := range c.Names() {
		if re.MatchString(name) {
			c.Unset(name)
			removed++
		}
	}
	return removed
}

// compileGlob turns a CMake globbing expression -- `*` and `?`, not a regular
// expression -- into one that can be matched.
func compileGlob(pattern string) (matcher, error) {
	var b strings.Builder
	b.WriteString("^")
	for _, r := range pattern {
		switch r {
		case '*':
			b.WriteString(".*")
		case '?':
			b.WriteString(".")
		default:
			b.WriteString(regexpQuoteRune(r))
		}
	}
	b.WriteString("$")
	return compileCMakeRegex(b.String())
}

// matcher is the small part of a compiled regexp this file needs.
type matcher interface {
	MatchString(string) bool
}

func regexpQuoteRune(r rune) string {
	if strings.ContainsRune(`\.+()|[]{}^$`, r) {
		return `\` + string(r)
	}
	return string(r)
}
